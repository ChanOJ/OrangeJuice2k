#!/usr/bin/env python3
"""Generate the Bunny Edge Script of legacy redirects from build-meta/url-map.json.

    python3 -I scripts/gen_edge_script.py           # writes infra/edge/redirects.js
    python3 -I scripts/gen_edge_script.py --check   # fails if the versioned file is stale (CI)

The old site answered `*.asp?query` URLs; the static archive has one file per page. The edge
script (a middleware of the pull zone, see infra/main.tf) answers those old URLs with a 301 to
the static path. The lookup is compacted: exact entries of the form `<script>?<param>=<number>`
whose target only differs by that number become a rule (template + set of known numbers), the
other entries stay exact. Keys are normalised the same way here and in the script (lower-case
path and parameter names, empty parameters dropped, parameters sorted); a clash of two old URLs
with different targets after normalisation is an error.

Standard library only. Test: node scripts/test_edge_script.mjs
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import parse_qsl, unquote, urlsplit

REPO = Path(__file__).resolve().parent.parent
URL_MAP = REPO / "build-meta" / "url-map.json"
OUT = REPO / "infra" / "edge" / "redirects.js"
MIN_RULE_SIZE = 8  # fewer numbered entries than this stay exact
ARCHIVED = "/archived.html"
# Removed features (url-map.json patterns): any other *.asp under these folders -> ARCHIVED.
ARCHIVED_PREFIXES = ["/admin/", "/handles/", "/search/", "/wap/"]
SDK = "https://esm.sh/@bunny.net/edgescript-sdk@0.13.0"


def normalise(path: str, query: str) -> tuple[str, list[tuple[str, str]]]:
    """Mirror of norm() in the script."""
    p = unquote(path).lower()
    params = sorted((n.lower(), v) for n, v in parse_qsl(query, keep_blank_values=True) if v != "")
    return p, params


def key_of(path: str, params: list[tuple[str, str]]) -> str:
    return path + ("?" + "&".join(f"{n}={v}" for n, v in params) if params else "")


def ranges(ids: list[int]) -> str:
    """[1, 2, 3, 7] -> "1-3,7" (base 10, parsed by the script at start-up)."""
    out, start, prev = [], None, None
    for i in ids:
        if start is None:
            start = prev = i
        elif i == prev + 1:
            prev = i
        else:
            out.append(f"{start}-{prev}" if prev > start else str(start))
            start = prev = i
    if start is not None:
        out.append(f"{start}-{prev}" if prev > start else str(start))
    return ",".join(out)


def build(doc: dict) -> tuple[dict[str, str], list[dict]]:
    exact: dict[str, str] = {}
    for old, new in doc["urls"].items():
        parts = urlsplit(old)
        path, params = normalise(parts.path, parts.query)
        k = key_of(path, params)
        if exact.get(k, new) != new:
            sys.exit(f"url-map clash after normalisation: {k} -> {exact[k]} and {new}")
        exact[k] = new

    groups: dict[tuple[str, str, str], dict[int, str]] = defaultdict(dict)
    for k, new in exact.items():
        path, _, query = k.partition("?")
        params = [tuple(x.split("=", 1)) for x in query.split("&")] if query else []
        if len(params) != 1:
            continue
        name, value = params[0]
        if not value.isdigit() or str(int(value)) != value or new.count(value) != 1:
            continue
        groups[(path, name, new.replace(value, "{}"))][int(value)] = k

    rules = []
    for (path, name, template), members in sorted(groups.items()):
        if len(members) < MIN_RULE_SIZE:
            continue
        for k in members.values():
            del exact[k]
        rules.append({"path": path, "param": name, "to": template, "ids": ranges(sorted(members))})
    return dict(sorted(exact.items())), rules


def render(doc: dict, source_sha: str) -> str:
    exact, rules = build(doc)
    data = {
        "exact": exact,
        "rules": rules,
        "archived": ARCHIVED,
        "archivedPrefixes": ARCHIVED_PREFIXES,
    }
    blob = json.dumps(data, indent=None, separators=(",", ":"), ensure_ascii=True)
    return f"""// GENERATED by scripts/gen_edge_script.py from build-meta/url-map.json
// (sha256 {source_sha}): do not edit, regenerate.
//
// Bunny Edge Script (middleware of the pull zone, infra/main.tf): old ASP URLs of
// www.ojuice.net (2000) -> 301 to their static page. Runs on origin requests only (cache
// misses; the pull zone caches per query string). Static paths pass through untouched.
//   - exact old URL (or numbered rule: view_article.asp?id=N, handle.asp?id=N...) -> 301
//   - gonlink.asp?u=<ojuice.net URL> -> resolved like that URL; external targets -> 404
//     (no open redirect on this domain)
//   - known script with an unknown query -> 301 to its query-less page (/index.asp?x -> /index.html)
//   - other *.asp under {", ".join(ARCHIVED_PREFIXES)} -> 301 {ARCHIVED} (removed features)
//   - any other *.asp, unknown numbers (/view_article.asp?id=99999) -> 404 with /404.html
// Test: node scripts/test_edge_script.mjs

import * as BunnySDK from "{SDK}";

// BEGIN resolve (pure, tested by scripts/test_edge_script.mjs)
const DATA = {blob};

function parseRanges(s) {{
  const set = new Set();
  for (const part of s.split(",")) {{
    if (!part) continue;
    const [a, b] = part.split("-").map(Number);
    for (let i = a; i <= (b === undefined ? a : b); i++) set.add(i);
  }}
  return set;
}}

const RULES = {{}};
for (const r of DATA.rules) {{
  (RULES[r.path] = RULES[r.path] || []).push({{ param: r.param, to: r.to, ids: parseRanges(r.ids) }});
}}

function norm(pathname, search) {{
  let path;
  try {{ path = decodeURIComponent(pathname); }} catch (e) {{ path = pathname; }}
  path = path.toLowerCase();
  const params = [];
  for (const [n, v] of new URLSearchParams(search)) if (v !== "") params.push([n.toLowerCase(), v]);
  params.sort((x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : x[1] < y[1] ? -1 : x[1] > y[1] ? 1 : 0));
  const key = path + (params.length ? "?" + params.map(([n, v]) => n + "=" + v).join("&") : "");
  return {{ path, params, key }};
}}

const OJ_HOSTS = new Set(["www.ojuice.net", "ojuice.net"]);
const NOT_FOUND = {{ status: 404 }};
const moved = (location) => ({{ status: 301, location }});

// -> null (serve the request as is), {{status: 301, location}} or {{status: 404}}.
function resolve(pathname, search, depth = 0) {{
  const {{ path, params, key }} = norm(pathname, search || "");
  const isAsp = path.endsWith(".asp");
  if (!isAsp && !search) {{
    // Fast path: static files. Only old folder URLs (/charts/, /search/...) are redirected.
    const t = DATA.exact[path];
    return t && path !== "/" && t !== path ? moved(t) : null;
  }}
  const exact = DATA.exact[key];
  if (exact) return moved(exact);
  if (!isAsp) return null; // static page with a query string (/search.html?q=...)
  const get = (name) => {{ const p = params.find(([n]) => n === name); return p ? p[1] : null; }};
  for (const r of RULES[path] || []) {{
    const v = get(r.param);
    if (v !== null && /^[0-9]{{1,9}}$/.test(v) && r.ids.has(Number(v))) return moved(r.to.replace("{{}}", String(Number(v))));
  }}
  if (path === "/gonlink.asp" && depth === 0) {{
    const u = get("u");
    if (u) {{
      let target;
      try {{ target = new URL(u, "http://www.ojuice.net/"); }} catch (e) {{ return NOT_FOUND; }}
      if (!OJ_HOSTS.has(target.hostname.toLowerCase())) return NOT_FOUND;
      const r = resolve(target.pathname, target.search, depth + 1);
      if (r) return r;
      return moved(target.pathname + target.search);
    }}
  }}
  // Numbered page that is not in the archive (news after the cut-off, unpublished people...).
  if ((RULES[path] || []).some((r) => get(r.param) !== null)) return NOT_FOUND;
  const bare = DATA.exact[path];
  if (bare) return moved(bare);
  if (DATA.archivedPrefixes.some((p) => path.startsWith(p))) return moved(DATA.archived);
  return NOT_FOUND;
}}
// END resolve

// A path that never exists in the storage zone: the origin then answers with its custom 404
// page (/404.html) and a real 404 status.
const MISSING = "/.legacy-url-not-in-archive";

BunnySDK.net.http.servePullZone().onOriginRequest((ctx) => {{
  const url = new URL(ctx.request.url);
  const r = resolve(url.pathname, url.search);
  if (!r) return Promise.resolve(ctx.request);
  if (r.status === 301) {{
    return Promise.resolve(new Response(null, {{
      status: 301,
      headers: {{ Location: r.location, "Cache-Control": "public, max-age=86400" }},
    }}));
  }}
  url.pathname = MISSING;
  url.search = "";
  return Promise.resolve(new Request(url.toString(), ctx.request));
}});
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if infra/edge/redirects.js is not up to date")
    args = ap.parse_args()
    raw = URL_MAP.read_bytes()
    text = render(json.loads(raw), hashlib.sha256(raw).hexdigest())
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="ascii") != text:
            print(f"{OUT.relative_to(REPO)} is stale: run python3 -I scripts/gen_edge_script.py")
            return 1
        print(f"{OUT.relative_to(REPO)} is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="ascii")
    exact, rules = build(json.loads(raw))
    print(f"{OUT.relative_to(REPO)}: {len(exact)} exact entries, {len(rules)} rules "
          f"({', '.join(r['path'] + '?' + r['param'] for r in rules)}), {len(text) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
